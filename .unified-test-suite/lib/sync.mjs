// canon/lib/sync.mjs — distribution: init a project, sync a project to a canon version, generate
// the project's layer/gate shortcut tasks, hash vendored files for the lock.
import { createHash } from 'node:crypto';
import {
  readFileSync, writeFileSync, existsSync, readdirSync, statSync, mkdirSync, cpSync, rmSync, mkdtempSync, appendFileSync, chmodSync,
} from 'node:fs';
import { execFileSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { ROOT, CANON_DIR, VENDOR_DIR, CONFIG_FILE, LOCK_FILE, loadConfig, readJson, canonVersion, sh } from './core.mjs';

const GENERATED = 'generated';
const notGenerated = (base) => (src) => { const rel = path.relative(base, src).split(path.sep).join('/'); return rel !== GENERATED && !rel.startsWith(`${GENERATED}/`); };
const ATTRS = `# unified-test-suite: vendored canon is byte-exact (lock hashes); never convert line endings\n${VENDOR_DIR}/** -text\nunified-test-suite.lock.json -text\n`;
function ensureGitattributes(proj) {
  const f = path.join(proj, '.gitattributes');
  const cur = existsSync(f) ? readFileSync(f, 'utf8') : '';
  if (!cur.includes(`${VENDOR_DIR}/** -text`)) appendFileSync(f, `${cur && !cur.endsWith('\n') ? '\n' : ''}${ATTRS}`);
}

/** Resolve a canon source (local checkout or git URL, optional ref) into a directory. */
export function fetchCanon(from, ref = null, { allowDirty = false } = {}) {
  const isUrl = /^[a-z]+:\/\//.test(from) || from.startsWith('git@');
  let src = isUrl ? null : path.resolve(from);
  let tmp = null;
  if (!isUrl && !ref && !allowDirty && existsSync(path.join(src, '.git')) && sh(`git -C ${JSON.stringify(src)} status --porcelain -- canon CHANGELOG.md`) !== '') {
    throw new Error(`${from} has uncommitted changes under canon/ — commit them, pass --ref <tag>, or --allow-dirty`);
  }
  if (isUrl || ref) {
    tmp = mkdtempSync(path.join(os.tmpdir(), 'uts-sync-'));
    const url = isUrl ? from : `file://${src}`;
    execFileSync('git', ['clone', '--quiet', '--depth', '1', ...(ref ? ['--branch', ref] : []), url, tmp], { stdio: 'inherit' });
    src = tmp;
  }
  if (!existsSync(path.join(src, 'canon', 'VERSION'))) throw new Error(`${from}${ref ? `@${ref}` : ''} is not a unified-test-suite checkout (canon/VERSION missing)`);
  return { src, tmp, isUrl };
}

/** Compare the vendored copy and the lock against the upstream canon at lock.ref (CI tamper check). */
export function verifyUpstream(from) {
  const lock = readJson(path.join(ROOT, LOCK_FILE), null);
  if (!lock) return [`${LOCK_FILE} missing`];
  const { src, tmp } = fetchCanon(from, lock.ref, { allowDirty: true });
  try {
    const up = hashTree(path.join(src, 'canon'));
    const errs = [];
    for (const [f, h] of Object.entries(up)) if (lock.files[f] !== h) errs.push(`lock entry for ${f} does not match upstream ${lock.ref ?? '(working tree)'}`);
    for (const f of Object.keys(lock.files)) if (!(f in up)) errs.push(`lock lists ${f}, which upstream ${lock.ref ?? ''} does not have`);
    return errs;
  } finally { if (tmp) rmSync(tmp, { recursive: true, force: true }); }
}

export function hashTree(dir) {
  const files = {};
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      const p = path.join(d, name);
      const rel = path.relative(dir, p).split(path.sep).join('/');
      if (rel === GENERATED || rel.startsWith(`${GENERATED}/`)) continue;
      if (statSync(p).isDirectory()) walk(p);
      else files[rel] = createHash('sha256').update(readFileSync(p)).digest('hex');
    }
  };
  walk(dir);
  return files;
}

function makeExecutable(dir) {
  for (const sub of ['bin', 'scripts']) {
    const d = path.join(dir, sub);
    if (!existsSync(d)) continue;
    for (const f of readdirSync(d)) if (/\.(sh|mjs)$/.test(f)) chmodSync(path.join(d, f), 0o755);
  }
}

// ------------------------------------------------------------------ gen
const yq = (s) => `'${String(s).replace(/'/g, "''")}'`;
export function renderGenerated(cfg) {
  const out = [
    '# GENERATED by `uts gen` from unified-test-suite.config.json — do not edit.',
    '# `uts check` fails when this file is out of sync with the config. Re-run: task uts:gen',
    "version: '3'",
    '',
    'tasks:',
  ];
  for (const [name, L] of Object.entries(cfg.layers)) {
    const d = L.description ? ` — ${L.description}` : '';
    out.push(`  test:${name}:`, `    desc: ${yq(`Layer ${name} (${L.runner}${L.needsStack ? ', needs stack' : ''})${d} → summary`)}`,
      '    cmds:', '      - task: uts:single', `        vars: { LAYER: ${yq(name)} }`);
  }
  for (const [name, layers] of Object.entries(cfg.groups ?? {})) {
    out.push(`  test:${name}:`, `    desc: ${yq(`Group ${name}: ${layers.join(', ')} → summary`)}`,
      '    cmds:', '      - task: uts:invalidate', `        vars: { TARGET: ${yq(name)} }`, '      - task: uts:set', `        vars: { LAYERS: ${yq(layers.join(' '))}, TARGET: ${yq(name)} }`);
  }
  for (const [name, g] of Object.entries(cfg.gates ?? {})) {
    const extra = [g.strict ? 'strict' : null, g.budgetSeconds ? `budget ${g.budgetSeconds}s` : null].filter(Boolean).join(', ');
    const d = g.description ? `${g.description} — ` : '';
    out.push(`  test:${name}:`, `    desc: ${yq(`Gate ${name}: ${d}${g.layers.join(', ')}${extra ? ` (${extra})` : ''} → summary`)}`,
      '    cmds:', '      - task: uts:invalidate', `        vars: { TARGET: ${yq(name)} }`, '      - task: uts:gate', `        vars: { GATE: ${yq(name)} }`);
  }
  return out.join('\n') + '\n';
}

export function gen({ dir = VENDOR_DIR, quiet = false } = {}) {
  const cfg = loadConfig();
  const file = path.join(ROOT, dir, GENERATED, 'Taskfile.yml');
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, renderGenerated(cfg));
  if (!quiet) console.log(`uts gen: wrote ${path.relative(ROOT, file)} (${Object.keys(cfg.layers).length} layers, ${Object.keys(cfg.groups ?? {}).length} groups, ${Object.keys(cfg.gates ?? {}).length} gates)`);
  return 0;
}

// ------------------------------------------------------------------ init
/** Run from the canon repo: `node canon/bin/uts.mjs init --target <project>`. */
export function init({ target, force = false, profile = 'fullstack' }) {
  if (!target) throw new Error('init: --target <project dir> is required');
  const repoRoot = path.resolve(CANON_DIR, '..');
  const templates = path.join(repoRoot, 'templates');
  if (!existsSync(templates)) throw new Error('init must run from a unified-test-suite repo checkout (templates/ not found); inside a project use `uts sync`');
  const proj = path.resolve(target);
  if (!existsSync(proj)) throw new Error(`target ${proj} does not exist`);
  const vendor = path.join(proj, VENDOR_DIR);
  if (existsSync(vendor) && !force) throw new Error(`${vendor} exists — use \`uts sync\` in the project (or --force)`);

  rmSync(vendor, { recursive: true, force: true });
  cpSync(CANON_DIR, vendor, { recursive: true, filter: notGenerated(CANON_DIR) });
  makeExecutable(vendor);
  writeLock(proj, vendor, { source: repoRoot, ref: null, commit: sh(`git -C ${JSON.stringify(repoRoot)} rev-parse HEAD`) || null });

  const profileFile = path.join(templates, 'profiles', `${profile}.json`);
  if (!existsSync(profileFile)) throw new Error(`unknown profile "${profile}" (have: ${readdirSync(path.join(templates, 'profiles')).map((f) => f.replace('.json', '')).join(', ')})`);
  const profileCfg = JSON.parse(readFileSync(profileFile, 'utf8'));
  profileCfg.project = path.basename(proj);
  const usesPlaywright = Object.values(profileCfg.layers).some((l) => l.runner === 'playwright');

  const created = []; const skipped = [];
  const place = (rel, write) => {
    const dst = path.join(proj, rel);
    if (existsSync(dst)) { skipped.push(rel); return; }
    mkdirSync(path.dirname(dst), { recursive: true });
    write(dst);
    created.push(rel);
  };
  place('unified-test-suite.config.json', (dst) => writeFileSync(dst, JSON.stringify(profileCfg, null, 2) + '\n'));
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const p = path.join(d, name);
      const rel = path.relative(templates, p).split(path.sep).join('/');
      if (rel === 'profiles') continue;
      if (statSync(p).isDirectory()) walk(p);
      else if (rel.includes('playwright') && !usesPlaywright) continue;
      else place(rel, (dst) => cpSync(p, dst));
    }
  };
  walk(templates);

  const gi = path.join(proj, '.gitignore');
  const giText = existsSync(gi) ? readFileSync(gi, 'utf8') : '';
  const need = ['test-results/', '__pycache__/', '.pytest_cache/', '.coverage'].filter((e) => !giText.split('\n').includes(e));
  if (need.length) appendFileSync(gi, `${giText && !giText.endsWith('\n') ? '\n' : ''}# unified-test-suite\n${need.join('\n')}\n`);
  ensureGitattributes(proj);

  const prevCwd = process.cwd();
  process.chdir(proj);
  try { execFileSync('node', [path.join(vendor, 'bin', 'uts.mjs'), 'gen'], { stdio: 'inherit' }); } finally { process.chdir(prevCwd); }

  console.log(`\nuts init: vendored canon ${canonVersion()} into ${path.relative(prevCwd, vendor) || vendor} (profile ${profile})`);
  if (created.length) console.log(`  created (project-owned, edit freely): ${created.join(', ')}`);
  if (skipped.length) console.log(`  kept existing: ${skipped.join(', ')}`);
  if (skipped.includes('Taskfile.yml')) console.log(`  ! add to your Taskfile.yml:\n      includes:\n        uts: { taskfile: ${VENDOR_DIR}/Taskfile.yml, flatten: true }`);
  console.log('\nNext: edit unified-test-suite.config.json, then `task uts:gen && task uts:check` — check lists every remaining adoption TODO.');
  return 0;
}

// ------------------------------------------------------------------ lock
export function writeLock(proj, vendor, { source, ref, commit }) {
  const lock = {
    canon: 'unified-test-suite',
    version: readFileSync(path.join(vendor, 'VERSION'), 'utf8').trim(),
    source: source && !/^[a-z]+:\/\//.test(source) && !source.startsWith('git@') ? '(local path)' : source,
    ref: ref ?? null,
    commit: commit ?? null,
    syncedAt: new Date().toISOString(),
    files: hashTree(vendor),
  };
  writeFileSync(path.join(proj, LOCK_FILE), JSON.stringify(lock, null, 2) + '\n');
  return lock;
}

export function verifyLock() {
  const vendor = path.join(ROOT, VENDOR_DIR);
  const lock = readJson(path.join(ROOT, LOCK_FILE), null);
  if (!lock) return { ok: false, errors: [`${LOCK_FILE} missing — vendored canon cannot be verified (run \`uts sync\`)`] };
  const actual = hashTree(vendor);
  const errors = [];
  for (const [f, h] of Object.entries(lock.files)) {
    if (!(f in actual)) errors.push(`${VENDOR_DIR}/${f} deleted locally`);
    else if (actual[f] !== h) errors.push(`${VENDOR_DIR}/${f} modified locally — change it upstream in unified-test-suite, then \`task uts:sync\``);
  }
  for (const f of Object.keys(actual)) if (!(f in lock.files)) errors.push(`${VENDOR_DIR}/${f} is not part of canon ${lock.version} — remove it (project files live outside ${VENDOR_DIR}/)`);
  return { ok: errors.length === 0, errors, lock };
}

// ------------------------------------------------------------------ sync
/** `uts sync --from <canon repo path | git url> [--ref vX.Y.Z] [--force]` (run inside a project). */
export function sync({ from, ref = null, force = false, allowDirty = false }) {
  if (!from) throw new Error('sync: --from <path to unified-test-suite checkout | git URL> is required');
  const { src, tmp, isUrl } = fetchCanon(from, ref, { allowDirty });
  const srcCanon = path.join(src, 'canon');

  const vendor = path.join(ROOT, VENDOR_DIR);
  const before = existsSync(vendor) ? verifyLock() : { ok: true, lock: null, errors: [] };
  if (!before.ok && !force) {
    throw new Error(`refusing to sync over local modifications:\n  ${before.errors.join('\n  ')}\nUpstream them first, or re-run with --force to discard.`);
  }
  const oldVersion = before.lock?.version ?? null;
  const oldFiles = before.lock?.files ?? {};
  rmSync(vendor, { recursive: true, force: true });
  cpSync(srcCanon, vendor, { recursive: true, filter: notGenerated(srcCanon) });
  makeExecutable(vendor);
  ensureGitattributes(ROOT);
  const commit = sh(`git -C ${JSON.stringify(src)} rev-parse HEAD`) || null;
  // Changelog entries newer than the previous version (read before the temp clone is removed).
  let notes = '';
  const clPath = path.join(src, 'CHANGELOG.md');
  if (existsSync(clPath)) {
    const lines = readFileSync(clPath, 'utf8').split('\n');
    const stop = oldVersion ? lines.findIndex((l) => /^##\s/.test(l) && l.includes(oldVersion)) : -1;
    const start = lines.findIndex((l) => /^##\s/.test(l));
    if (start >= 0) notes = lines.slice(start, stop > start ? stop : Math.min(lines.length, start + 40)).join('\n').trim();
  }
  const lock = writeLock(ROOT, vendor, { source: isUrl ? from : (tmp ? `file://${path.resolve(from)}` : from), ref, commit });
  if (tmp) rmSync(tmp, { recursive: true, force: true });

  const added = Object.keys(lock.files).filter((f) => !(f in oldFiles));
  const removed = Object.keys(oldFiles).filter((f) => !(f in lock.files));
  const changed = Object.keys(lock.files).filter((f) => f in oldFiles && oldFiles[f] !== lock.files[f]);
  console.log(`uts sync: ${oldVersion ?? '(none)'} → ${lock.version}${ref ? ` (${ref})` : ''}${commit ? ` @ ${commit.slice(0, 10)}` : ''}`);
  console.log(`  files: +${added.length} ~${changed.length} -${removed.length}`);
  if (notes && oldVersion !== lock.version) console.log(`\n${notes}\n\n  ↑ changelog since ${oldVersion ?? 'install'} — act on every line marked MIGRATION`);
  gen({ quiet: true });
  console.log('  regenerated .unified-test-suite/generated/Taskfile.yml — now run `task uts:check`');
  return 0;
}
